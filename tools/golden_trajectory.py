"""The golden full-trajectory Runtime domain: what to freeze and how to compare it.

Drives shr_pybind's Runtime over scripted PlayerState profiles (with notify events) and describes the
sampled physiology trajectory plus the fired-beat sequence as a manifest. This oracle locks the whole
Runtime.step path -- simulation, the in-Step RhythmInput derivation, rhythm, and mapping -- end to end.
Independent C++ behavioral coverage lives in RuntimeTests.cpp / SimulationTests.cpp; this golden anchors
full trajectories.

Simulation is deterministic and only rhythm draws from the seeded RNG, so scenarios are reproducible.
The golden is generated by the binding itself. Snapshots are sampled at the scenario interval; beats are
recorded in full. Values are stored rounded and compared at a tolerance.

One golden domain; tools/golden_registry.py describes the surface it exposes.
"""
from __future__ import annotations

from pathlib import Path

from trajectory_fixtures import (
    BEAT_FIELDS,
    SNAPSHOT_FIELDS,
    TRAJECTORY_SCENARIOS,
)

ROOT = Path(__file__).resolve().parent.parent

ID = "trajectory"
MANIFEST = ROOT / "tests" / "golden" / "trajectory.json"

ATOL = 1.0e-5

_NOTIFY = {
    "combat_entry": lambda rt, _d: rt.notify_combat_entry(),
    "hit": lambda rt, _d: rt.notify_hit(),
    "jump": lambda rt, _d: rt.notify_jump(),
    "sleep": lambda rt, d: rt.notify_sleep(d),
    "fast_travel": lambda rt, d: rt.notify_fast_travel(d),
}


def _round(value):
    return None if value is None else round(float(value), 6)


def _active_player(module, scenario, t: float):
    kwargs: dict = {}
    for segment in scenario.segments:
        if segment.start <= t:
            kwargs = segment.player
    return module.PlayerState(**kwargs)


def _run(module, scenario) -> dict:
    rt = module.Runtime(
        resting_heart_rate=scenario.resting_hr,
        maximum_heart_rate=scenario.max_hr,
        arrhythmia_susceptibility=scenario.arrhythmia_susceptibility,
        seed=scenario.seed,
    )
    rt.init()
    delta = 1.0 / scenario.fps
    frames = int(round(scenario.seconds * scenario.fps))
    interval = max(1, int(round(scenario.snapshot_interval_s * scenario.fps)))
    pending = sorted(scenario.events, key=lambda event: event.time)
    event_index = 0

    snapshots: list[dict] = []
    beats: list[dict] = []
    for frame in range(frames):
        t = frame * delta
        while event_index < len(pending) and pending[event_index].time < (frame + 1) * delta:
            event = pending[event_index]
            _NOTIFY[event.method](rt, event.duration)
            event_index += 1

        result = rt.step(
            player=_active_player(module, scenario, t),
            delta_seconds=delta,
            output_enabled=True,
        )
        if frame % interval == 0:
            snapshot = {"frame": frame}
            for name in SNAPSHOT_FIELDS:
                snapshot[name] = _round(getattr(result.physiology, name))
            snapshots.append(snapshot)
        if result.beat is not None:
            beat = {"frame": frame}
            for name in BEAT_FIELDS:
                value = getattr(result.beat.event, name)
                beat[name] = value if name == "kind" else _round(value)
            beats.append(beat)
    return {"snapshots": snapshots, "beats": beats}


def build(module) -> dict:
    return {
        "_comment": (
            "Golden full-trajectory Runtime output from the compiled shr_core via shr_pybind "
            "(Release-Clang, deterministic). Regenerate: python tools/capture_goldens.py trajectory"
        ),
        "scenarios": {name: _run(module, sc) for name, sc in TRAJECTORY_SCENARIOS.items()},
    }


def _diff_value(label: str, expected, actual, problems: list[str]) -> None:
    if isinstance(expected, str) or isinstance(actual, str) or expected is None or actual is None:
        if expected != actual:
            problems.append(f"{label}: golden {expected!r} != core {actual!r}")
    elif abs(float(expected) - float(actual)) > ATOL:
        problems.append(f"{label}: golden {expected} != core {actual}")


def _diff_rows(label: str, kind_fields, exp_rows, act_rows, problems: list[str]) -> None:
    if len(exp_rows) != len(act_rows):
        problems.append(f"{label}: count golden {len(exp_rows)} != core {len(act_rows)}")
        return
    for i, (exp, act) in enumerate(zip(exp_rows, act_rows)):
        if exp.get("frame") != act.get("frame"):
            problems.append(f"{label}[{i}]: frame golden {exp.get('frame')} != core {act.get('frame')}")
        for name in kind_fields:
            _diff_value(f"{label}[{i}].{name}", exp.get(name), act.get(name), problems)


def diff(expected: dict, actual: dict) -> list[str]:
    problems: list[str] = []
    exp_scenarios = expected.get("scenarios", {})
    act_scenarios = actual.get("scenarios", {})
    for name in TRAJECTORY_SCENARIOS:
        exp = exp_scenarios.get(name, {})
        act = act_scenarios.get(name, {})
        _diff_rows(f"{name}/snapshots", SNAPSHOT_FIELDS, exp.get("snapshots", []), act.get("snapshots", []), problems)
        _diff_rows(f"{name}/beats", BEAT_FIELDS, exp.get("beats", []), act.get("beats", []), problems)
    return problems


def summary(manifest: dict) -> list[str]:
    lines = []
    for name, data in manifest["scenarios"].items():
        kinds = ", ".join(sorted({beat["kind"] for beat in data["beats"]})) or "none"
        lines.append(f"{name}: {len(data['snapshots'])} snapshots, {len(data['beats'])} beats ({kinds})")
    return lines
